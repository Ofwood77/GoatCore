static int32_t find_named_id(const mc_minecraft_named_id_t *table, size_t count, const char *name) {
    if (!name) return -1;
    for (size_t i = 0; i < count; i++) {
        if (strcmp(table[i].name, name) == 0) return table[i].id;
    }
    return -1;
}

int32_t mc_minecraft_packet_id(mc_proto_state_t state, mc_minecraft_packet_direction_t direction, const char *name) {
    if (!name) return -1;
    for (size_t i = 0; i < sizeof(mc_minecraft_packets) / sizeof(mc_minecraft_packets[0]); i++) {
        const mc_minecraft_packet_entry_t *entry = &mc_minecraft_packets[i];
        if (entry->state == state && entry->direction == direction && strcmp(entry->name, name) == 0) return entry->id;
    }
    return -1;
}

const char *mc_minecraft_packet_name(mc_proto_state_t state, mc_minecraft_packet_direction_t direction, int32_t id) {
    for (size_t i = 0; i < sizeof(mc_minecraft_packets) / sizeof(mc_minecraft_packets[0]); i++) {
        const mc_minecraft_packet_entry_t *entry = &mc_minecraft_packets[i];
        if (entry->state == state && entry->direction == direction && entry->id == id) return entry->name;
    }
    return NULL;
}

