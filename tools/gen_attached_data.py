#!/usr/bin/env python3
"""Build immutable 26.1.1 support/shape/float tables from audit_attached_blocks.
Run the Java auditor against the official inner server JAR, never GoatCore.
"""
import argparse
import hashlib
from pathlib import Path


def generate(source, destination, fixture):
    raw = source.read_bytes()
    rows = [line.split() for line in raw.decode().splitlines()]
    supports = {int(r[1]): int(r[2]) for r in rows if r[0] == 'S'}
    trig = {int(r[1]): r[2] for r in rows if r[0] == 'T'}
    assert set(supports) == set(range(29873))
    assert set(trig) == set(range(65536))
    families = sorted((r[1], *map(int, r[2:])) for r in rows if r[0] == 'F')
    light = {int(r[1]): int(r[2]) for r in rows if r[0] == 'L'}
    shapes = {}
    for r in rows:
        if r[0] != 'H':
            continue
        state, kind, count, *boxes = map(int, r[1:])
        assert 0 <= count <= 2 and len(boxes) == 6 * count
        assert all(0 <= n <= 32 for n in boxes)
        shapes[state, kind] = [boxes[i:i+6] for i in range(0, len(boxes), 6)]
    out = ['/* Generated by tools/gen_attached_data.py; official 26.1.1. */',
           '/* Input SHA256: ' + hashlib.sha256(raw).hexdigest() + ' */',
           'static const mc_attached_family_t attached_families[] = {']
    for name, kind, item, default in families:
        out.append(f'    {{"{name}",{kind},{item},{default}}},')
    out += ['};', 'static const uint32_t face_support[29873] = {']
    for i in range(0, 29873, 16):
        out.append('    ' + ','.join(str(supports[j]) for j in range(i, min(i+16,29873))) + ',')
    out += ['};', 'static const struct attached_shape attached_shapes[] = {']
    for state in sorted(light):
        all_boxes = []
        for kind in range(2):
            boxes = shapes[state, kind]
            all_boxes.append('{' + str(len(boxes)) + ',{' + ','.join('{' + ','.join(map(str,b)) + '}' for b in boxes or [[0]*6]) + '}}')
        out.append(f'    {{{state},{light[state]},{{' + ','.join(all_boxes) + '}},')
    out += ['};', '/* Mth uses a quantized float table, including at angle boundaries. */',
            'static const uint32_t look_sin_bits[65536] = {']
    for i in range(0, 65536, 8):
        out.append('    ' + ','.join('0x' + trig[j] + 'u' for j in range(i, i+8)) + ',')
    out += ['};', '']
    destination.write_text('\n'.join(out))
    # Keep all support entries and official reference observations independently
    # readable by tests; sine bits are already preserved in the generated table.
    fixture.write_text(''.join('\t'.join(r)+'\n' for r in rows if r[0] != 'T'))


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('input', type=Path)
    p.add_argument('--output', type=Path, default=Path('src/generated/generated_attached_data.h'))
    p.add_argument('--fixture', type=Path, default=Path('tests/fixtures/vanilla-26.1.1-attached.tsv'))
    a = p.parse_args()
    generate(a.input, a.output, a.fixture)
